export const BIBLE: Author = { key: "bible", name: "The Bible", forms: [], kind: "scripture" };

const byForm = new Map<string, Author>();
for (const a of AUTHORS) for (const f of a.forms) byForm.set(foldForCompare(f), a);

/**
 * Rule: a Scripture reference (an optional book number, a book of the Bible,
 * then chapter and verse: "Ps. xix. 1", "1 Cor. xii. 5", "Judges xiii. 15")
 * belongs to The Bible; otherwise the printed author, folded, is looked up in
 * the table. Unknown authors keep their printed form as name, with a key
 * made from it; `known` says whether the table had it.
 */
export function normaliseAuthor(printed: string): { key: string; name: string; ref: string | null; known: boolean } {
  const p = printed.trim().replace(/\.$/, "");
  const scripture = /^(?:([1-4])\s+)?([A-Z][a-z]+)\.?\s+([ivxlcdm]+\.?\s*\d+(?:[,.-]\s*\d+)*)$/.exec(p);
  if (scripture && BOOKS[scripture[2]!]) {
    // Jer. could be Jeremiah or Jer. Taylor; a chapter and verse decide it.
    return { key: BIBLE.key, name: BIBLE.name, ref: `${scripture[1] ? scripture[1] + " " : ""}${BOOKS[scripture[2]!]} ${scripture[3]}`, known: true };
  }
  const a = byForm.get(foldForCompare(p));
  if (a) return { key: a.key, name: a.name, ref: null, known: true };
  const key = p.toLowerCase().normalize("NFKD").replace(/\p{M}/gu, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return { key: key || "unknown", name: p, ref: null, known: false };
}
